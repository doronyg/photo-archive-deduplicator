// SQLDelight output lives under build/, but Android Studio presents it like source.
// Stamp every generated file with a "do not edit" header naming its source.
// See src/commonMain/sqldelight/README.md.
val sqlDelightSourceDir: File = file("src/commonMain/sqldelight")
val sqlDelightConfigFile: File = buildFile
tasks.withType<app.cash.sqldelight.gradle.SqlDelightTask>().configureEach {
    val generatedDir = outputDirectory
    val generatorTask = path
    val projectDir = projectDir
    doLast {
        val marker = "GENERATED FILE - DO NOT EDIT"
        val sqFiles = sqlDelightSourceDir.walkTopDown().filter { it.extension == "sq" }.sortedBy { it.name }.toList()
        fun rel(file: File) = file.relativeTo(projectDir.parentFile).invariantSeparatorsPath

        fun sourcesOf(generated: File): List<String> {
            val stem = generated.nameWithoutExtension.removeSuffix("Queries")
            val byName = sqFiles.filter { it.nameWithoutExtension == stem }
            val byTable = sqFiles.filter {
                Regex("""CREATE\s+TABLE\s+$stem\b""", RegexOption.IGNORE_CASE).containsMatchIn(it.readText())
            }
            return (byName + byTable).distinct().map(::rel).ifEmpty {
                // Database-level classes are built from every .sq file plus the Gradle config
                sqFiles.map(::rel) + "${rel(sqlDelightConfigFile)} (sqldelight { databases { ... } } block)"
            }
        }

        generatedDir.get().asFile.walkTopDown().filter { it.extension == "kt" }.forEach { generated ->
            val text = generated.readText()
            if (marker in text) return@forEach
            val header = buildString {
                appendLine("// ============================================================================")
                appendLine("// $marker")
                appendLine("//")
                appendLine("// Generated by the SQLDelight Gradle plugin (task $generatorTask).")
                appendLine("// Source:")
                sourcesOf(generated).forEach { appendLine("//   - $it") }
                appendLine("//")
                appendLine("// Manual edits are lost on the next build. This applies to people and AI")
                appendLine("// assistants alike: change the source above, then rebuild or run")
                appendLine("//   ./gradlew $generatorTask")
                appendLine("// Details: ${rel(File(sqlDelightSourceDir, "README.md"))}")
                appendLine("// ============================================================================")
                appendLine()
            }
            generated.writeText(header + text)
        }
    }
}
